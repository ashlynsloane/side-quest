import type { Exercise } from '@circuit/domain';

const CREATED_AT = '2026-08-08T00:00:00.000Z';

type MachineExerciseInput = {
  id: string;
  slug: string;
  name: string;
  aliases?: string[];
  category: string;
  description: string;
  setup: string;
  execution: string;
  cues: string[];
  mistakes: string[];
  bodyRegions: Exercise['bodyRegions'];
  jointLoads: Exercise['jointLoads'];
  movementPatterns: Exercise['movementPatterns'];
  avoidanceTags?: Exercise['avoidanceTags'];
  stationRoles: Exercise['stationRoles'];
  equipmentId:
    | 'cable_machine'
    | 'leg_press'
    | 'hack_squat_machine'
    | 'leg_extension_machine'
    | 'leg_curl_machine'
    | 'calf_raise_machine'
    | 'assisted_pullup_machine'
    | 'chest_press_machine'
    | 'row_machine';
  equipmentOptionId: string;
  equipmentLabel: string;
  target?: number;
  minimum?: number;
  maximum?: number;
  loadGuidance?: string;
};

function machineExercise(input: MachineExerciseInput): Exercise {
  const target = input.target ?? 8;
  const minimum = input.minimum ?? 6;
  const maximum = input.maximum ?? 10;
  return {
    id: input.id,
    slug: input.slug,
    name: input.name,
    aliases: input.aliases ?? [],
    status: 'active',
    classification: 'equipment',
    category: input.category,
    shortDescription: input.description,
    instructions: {
      setup: [input.setup],
      execution: [input.execution],
      cues: input.cues,
      commonMistakes: input.mistakes,
    },
    bodyRegions: input.bodyRegions,
    jointLoads: input.jointLoads,
    movementPatterns: input.movementPatterns,
    avoidanceTags: input.avoidanceTags ?? [],
    laterality: 'bilateral',
    stationRoles: input.stationRoles,
    equipmentOptions: [{
      id: input.equipmentOptionId,
      label: input.equipmentLabel,
      items: [{ equipmentId: input.equipmentId, quantity: 1 }],
    }],
    prescriptions: [{
      id: `${input.slug}_strength`,
      style: 'strength',
      mode: 'reps',
      target,
      minimum,
      maximum,
      unit: 'total',
      estimatedSeconds: 45,
      loadGuidance: input.loadGuidance ?? 'Use a challenging load that leaves about 2 good repetitions in reserve.',
    }],
    impactLevel: 0,
    balanceDemand: 0,
    cardiovascularDemand: input.stationRoles.includes('primary_strength') ? 2 : 1,
    technicalComplexity: 1,
    suitableForAmrap: false,
    suitableForTravel: false,
    suitableForBeginners: true,
    substitutionGroupIds: [],
    compatibility: { maximumAppearancesPerWorkout: 1 },
    media: [],
    defaultEnabled: true,
    contentVersion: 1,
    createdAt: CREATED_AT,
    updatedAt: CREATED_AT,
  };
}

