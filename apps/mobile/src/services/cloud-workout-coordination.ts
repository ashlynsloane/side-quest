import { supabase } from './supabase';

/**
 * This feature must be explicitly enabled only AFTER the Supabase lease
 * migration is deployed. It blocks simultaneous *active sessions*, not total
 * same-day work across devices: that requires synchronized training history.
 */
export function cloudWorkoutLeasesEnabled(): boolean {
  return process.env.EXPO_PUBLIC_DISTRIBUTED_WORKOUT_LOCKS === 'true';
}

export interface RemoteWorkoutPrescription {
  trainingDate: string;
  sessionId: string;
  minutes: number;
  regions: string[];
}

export interface CloudWorkoutLease {
  leaseId: string;
  deviceId: string;
  expiresAt: string;
}

export interface WorkoutLeaseRpc {
  rpc(name: string, params: Record<string, unknown>): Promise<{
    data: unknown;
    error: { message: string } | null;
  }>;
}

const DEVICE_KEY = 'sidequest.cloud-workout-device.v1';
const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

function parseRows(data: unknown): Record<string, unknown> {
  const row = Array.isArray(data) ? data[0] : data;
  if (!row || typeof row !== 'object') {
    throw new Error('Workout coordination returned an invalid response.');
  }
  return row as Record<string, unknown>;
}

function getDeviceTag(): string {
  const storage = (globalThis as { localStorage?: Storage }).localStorage;
  if (!storage) throw new Error('Durable local storage is required for cloud workout coordination.');
  const existing = storage.getItem(DEVICE_KEY);
  if (existing && existing.length <= 128 && existing.length > 0) return existing;
  // This is only a device label, not an authentication credential. The actual
  // lease ID is a cryptographically random UUID generated by PostgreSQL.
  const tag = `sq-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 12)}`;
  storage.setItem(DEVICE_KEY, tag);
  return tag;
}

function requireBackend(rpc?: WorkoutLeaseRpc): WorkoutLeaseRpc {
  if (rpc) return rpc;
  if (!supabase) throw new Error('Cloud workout coordination requires an authenticated Supabase connection.');
  return supabase as unknown as WorkoutLeaseRpc;
}

async function request(
  rpc: WorkoutLeaseRpc, name: string, params: Record<string, unknown>,
): Promise<Record<string, unknown>> {
  const response = await rpc.rpc(name, params);
  if (response.error) throw new Error(`Cloud workout coordination failed: ${response.error.message}`);
  return parseRows(response.data);
}

export function validCloudWorkoutLease(lease: unknown): lease is CloudWorkoutLease {
  if (!lease || typeof lease !== 'object') return false;
  const value = lease as Partial<CloudWorkoutLease>;
  return typeof value.leaseId === 'string' && UUID_PATTERN.test(value.leaseId)
    && typeof value.deviceId === 'string' && value.deviceId.length > 0
    && value.deviceId.length <= 128
    && typeof value.expiresAt === 'string'
    && Number.isFinite(Date.parse(value.expiresAt));
}

/** An unsuccessful RPC, malformed response or another-device lease denies a start. */
export async function acquireCloudWorkoutLease(
  workoutId: string, rpc?: WorkoutLeaseRpc, prescription?: RemoteWorkoutPrescription,
): Promise<CloudWorkoutLease> {
  if (!workoutId || workoutId.length > 128) throw new Error('Invalid workout identity.');
  const deviceId = getDeviceTag();
  if (cloudWorkoutLeasesEnabled() && (!prescription || !prescription.sessionId ||
      !/^\\d{4}-\\d{2}-\\d{2}$/.test(prescription.trainingDate) ||
      !Number.isInteger(prescription.minutes) || prescription.minutes <= 0 ||
      prescription.regions.length === 0)) {
    throw new Error('A synchronized prescription is required before acquiring a cloud workout lease.');
  }
  const coordinated = cloudWorkoutLeasesEnabled();
  const row = await request(requireBackend(rpc),
    coordinated ? 'acquire_training_workout_lease_v2' : 'acquire_training_workout_lease', {
    p_workout_id: workoutId,
    p_device_id: deviceId,
    ...(coordinated && prescription ? {
      p_training_date: prescription.trainingDate,
      p_session_id: prescription.sessionId,
      p_planned_minutes: prescription.minutes,
      p_regions: prescription.regions,
    } : {}),
  });
  if (row.granted !== true) {
    throw new Error(typeof row.reason === 'string' && row.reason
      ? row.reason
      : 'Another device has an active workout. Finish that session or wait for its lease to expire.');
  }
  const lease = {
    leaseId: row.lease_id,
    deviceId,
    expiresAt: row.expires_at,
  };
  if (!validCloudWorkoutLease(lease) || Date.parse(lease.expiresAt) <= Date.now()) {
    throw new Error('Workout coordination returned an invalid or expired lease.');
  }
  return lease;
}

/** A paused/expired lease cannot be renewed: training remains paused. */
export async function renewCloudWorkoutLease(
  lease: CloudWorkoutLease, rpc?: WorkoutLeaseRpc,
): Promise<CloudWorkoutLease> {
  if (!validCloudWorkoutLease(lease)) throw new Error('Cloud workout lease is invalid.');
  const row = await request(requireBackend(rpc),
    cloudWorkoutLeasesEnabled()
      ? 'renew_training_workout_lease_v2'
      : 'renew_training_workout_lease', {
    p_lease_id: lease.leaseId, p_device_id: lease.deviceId,
  });
  const renewed = { ...lease, expiresAt: row.expires_at };
  if (row.renewed !== true || !validCloudWorkoutLease(renewed) ||
      Date.parse(renewed.expiresAt) <= Date.now()) {
    throw new Error(typeof row.reason === 'string' && row.reason
      ? row.reason : 'Cloud workout lease was lost or expired. Pause training and review the session.');
  }
  return renewed;
}

export async function releaseCloudWorkoutLease(
  lease: CloudWorkoutLease, rpc?: WorkoutLeaseRpc,
): Promise<void> {
  if (!validCloudWorkoutLease(lease)) throw new Error('Cloud workout lease is invalid.');
  const response = await requireBackend(rpc).rpc('release_training_workout_lease', {
    p_lease_id: lease.leaseId, p_device_id: lease.deviceId,
  });
  if (response.error) throw new Error(`Cloud workout lease release failed: ${response.error.message}`);
  // false means this lease was already lost or expired; it cannot delete
  // another device's lock, and is safe to consider released locally.
}


export interface CloudLeaseMonitorOptions {
  initialLease: CloudWorkoutLease;
  renew(lease: CloudWorkoutLease): Promise<CloudWorkoutLease>;
  persist(lease: CloudWorkoutLease): Promise<void>;
  onVerified(lease: CloudWorkoutLease): void;
  onLost(reason: string): void;
  subscribeForeground(check: () => void): () => void;
  intervalMs?: number;
  now?: () => number;
}

/**
 * Runs an immediate server renewal before allowing workout playback, then
 * checks every 30 seconds and on foreground. Local timestamps never extend
 * an expiring server lease. Network failures and lost tokens pause playback.
 * It must be restarted with a fresh session after a lost lease.
 */
export function createCloudWorkoutLeaseMonitor(options: CloudLeaseMonitorOptions) {
  let current = options.initialLease;
  let active = false;
  let lost = false;
  let pending = false;
  let checking = false;
  let generation = 0;
  let interval: ReturnType<typeof setInterval> | undefined;
  let unsubscribe: (() => void) | undefined;
  const now = options.now ?? Date.now;
  const intervalMs = options.intervalMs ?? 30_000;
  if (!Number.isFinite(intervalMs) || intervalMs < 1000 || intervalMs >= 90_000) {
    throw new Error('Cloud lease monitoring interval must be between 1 and 90 seconds.');
  }

  const lose = (reason: string) => {
    if (!active || lost) return;
    lost = true;
    options.onLost(reason);
  };

  const check = async (): Promise<void> => {
    if (!active || lost) return;
    if (!validCloudWorkoutLease(current) || Date.parse(current.expiresAt) <= now()) {
      lose('Cloud workout coordination expired. Stop training and review the session.');
      return;
    }
    if (checking) {
      pending = true;
      return;
    }
    checking = true;
    const token = generation;
    try {
      const next = await options.renew(current);
      if (!active || lost || token !== generation) return;
      if (!validCloudWorkoutLease(next) || next.leaseId !== current.leaseId ||
          next.deviceId !== current.deviceId || Date.parse(next.expiresAt) <= now()) {
        throw new Error('The cloud workout lease is invalid or was replaced.');
      }
      await options.persist(next);
      if (!active || lost || token !== generation) return;
      current = next;
      options.onVerified(next);
    } catch (cause) {
      if (active && !lost && token === generation) {
        lose(cause instanceof Error ? cause.message : 'Cloud workout lease verification failed.');
      }
    } finally {
      checking = false;
      if (pending && active && !lost && token === generation) {
        pending = false;
        void check();
      }
    }
  };

  return {
    getLease: () => current,
    isLost: () => lost,
    check,
    start(): () => void {
      if (active) throw new Error('Cloud workout monitor is already running.');
      if (!validCloudWorkoutLease(current)) {
        throw new Error('Cloud workout monitor requires a valid server-issued lease.');
      }
      active = true;
      generation += 1;
      void check();
      interval = setInterval(() => { void check(); }, intervalMs);
      unsubscribe = options.subscribeForeground(() => { void check(); });
      return () => {
        active = false;
        generation += 1;
        pending = false;
        if (interval) clearInterval(interval);
        unsubscribe?.();
      };
    },
  };
}
